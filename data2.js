// レッスンの中身。ITEMS = 覚える項目、UNITS = ホームに並ぶレッスン一覧
// item: { id, kind(letter|syl|pat|word), ko, read, mean, say, note, grp }
const ITEMS = {};
const BY_KIND = { letter: [], syl: [], pat: [], word: [] };
function addItem(kind, o) {
  o.kind = kind; o.id = kind[0] + ':' + o.ko;
  ITEMS[o.id] = o; BY_KIND[kind].push(o);
  return o;
}

// ---------- 1. 文字 ----------
GROUPS.forEach(function (g) {
  g.items.forEach(function (it) {
    addItem('letter', { ko: it.ch, read: it.kana, say: it.say, note: it.note, grp: g.id });
  });
});
function letters(gi, a, b) {
  return GROUPS[gi].items.slice(a, b).map(function (it) { return ITEMS['l:' + it.ch]; });
}

