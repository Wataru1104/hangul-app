const SYL_V = [0, 4, 8, 13, 18, 20];             // ㅏ ㅓ ㅗ ㅜ ㅡ ㅣ
const SYL_VCH = ['ㅏ', 'ㅓ', 'ㅗ', 'ㅜ', 'ㅡ', 'ㅣ'];
const SYL_HINT = ['', '（口を大きく）', '（口を丸く）', '（口を丸く）', '（口を横に）', ''];
const SYL_ROWS = [
  ['ㄱ', 0, ['カ', 'コ', 'コ', 'ク', 'ク', 'キ']],
  ['ㄴ', 2, ['ナ', 'ノ', 'ノ', 'ヌ', 'ヌ', 'ニ']],
  ['ㄷ', 3, ['タ', 'ト', 'ト', 'トゥ', 'トゥ', 'ティ']],
  ['ㄹ', 5, ['ラ', 'ロ', 'ロ', 'ル', 'ル', 'リ']],
  ['ㅁ', 6, ['マ', 'モ', 'モ', 'ム', 'ム', 'ミ']],
  ['ㅂ', 7, ['パ', 'ポ', 'ポ', 'プ', 'プ', 'ピ']],
  ['ㅅ', 9, ['サ', 'ソ', 'ソ', 'ス', 'ス', 'シ']],
  ['ㅇ', 11, ['ア', 'オ', 'オ', 'ウ', 'ウ', 'イ']],
  ['ㅈ', 12, ['チャ', 'チョ', 'チョ', 'チュ', 'チュ', 'チ']],
  ['ㅎ', 18, ['ハ', 'ホ', 'ホ', 'フ', 'フ', 'ヒ']]
];
function compose(l, v, t) { return String.fromCharCode(0xAC00 + (l * 21 + v) * 28 + (t || 0)); }
SYL_ROWS.forEach(function (r) {
  r[2].forEach(function (k, vi) {
    var ko = compose(r[1], SYL_V[vi]);
    addItem('syl', { ko: ko, read: k + SYL_HINT[vi], say: ko, c: r[0], v: SYL_VCH[vi], note: r[0] + ' + ' + SYL_VCH[vi] });
  });
});
function sylRows(a, b) {
  var out = [];
  SYL_ROWS.slice(a, b).forEach(function (r) {
    r[2].forEach(function (k, vi) { out.push(ITEMS['s:' + compose(r[1], SYL_V[vi])]); });
  });
  return out;
}

