function ex(ko, ja) {
  return '<div class="exrow" data-say="' + ko + '"><span class="exk">' + ko + '</span><span class="exj">' + ja + '</span><span class="exs">🔊</span></div>';
}
function ord(ja, ko, extra) {
  return { kind: 'order', ja: ja, tiles: ko.split(' '), extra: extra || [], say: ko };
}
function fill(big, options, answer, why) {
  return { kind: 'choice', prompt: '（　）に入るのは どれ？', big: big, bigCls: 'sent', options: options, answer: answer, why: why };
}
function mean(ko, ja, wrongs) {
  return { kind: 'choice', prompt: 'どんな意味？', big: ko, bigCls: 'sent', options: [ja].concat(wrongs), answer: ja, say: ko, listen: ko };
}
function pick(prompt, ja, ok, wrongs, why) {
  return { kind: 'choice', prompt: prompt, big: ja, bigCls: 'sent jp', options: [ok].concat(wrongs), answer: ok, say: ok, why: why };
}

